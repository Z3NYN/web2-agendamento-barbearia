    void bloqueiaInicializacaoQuandoMigracaoObrigatoriaFalha(@TempDir Path tempDir) throws Exception {
        Path dbArquivo = tempDir.resolve("somente_leitura");
        String urlEscrita = "jdbc:h2:file:" + dbArquivo.toAbsolutePath();
        try (Connection conn = DriverManager.getConnection(urlEscrita, "sa", "");
             Statement stmt = conn.createStatement()) {
            stmt.execute("CREATE TABLE usuario (id BIGINT PRIMARY KEY, username VARCHAR(255) NOT NULL)");
            stmt.execute("INSERT INTO usuario (id, username) VALUES (1, 'travado')");
        }

        String urlSomenteLeitura = urlEscrita + ";ACCESS_MODE_DATA=r";
        String vapidArquivo = tempDir.resolve("vapid_falha.properties").toAbsolutePath().toString();

        assertThatThrownBy(() -> {
            try (ConfigurableApplicationContext ignored = iniciarAplicacao(urlSomenteLeitura, vapidArquivo)) {
                // Não deve alcançar este ponto.
            }
        }).hasRootCauseInstanceOf(SQLException.class);
    }

    private ConfigurableApplicationContext iniciarAplicacao(String jdbcUrl, String vapidArquivo) {
        return new SpringApplicationBuilder(BraullyWeb2FullstackApplication.class)
                .run(
                        "--server.port=0",
                        "--server.address=127.0.0.1",
                        "--spring.datasource.url=" + jdbcUrl,
                        "--spring.datasource.username=sa",
                        "--spring.datasource.password=",
                        "--spring.jpa.hibernate.ddl-auto=update",
                        "--app.demo=false",
                        "--jwt.secret=chave-teste-migracao-legado-000001",
                        "--app.vapid.arquivo=" + vapidArquivo
                );
    }

    private String login(int porta, String username, String senha) throws Exception {
        var body = json.writeValueAsString(Map.of("username", username, "senha", senha));
        var req = HttpRequest.newBuilder(URI.create("http://127.0.0.1:" + porta + "/api/login"))
                .header("Content-Type", "application/json")
                .POST(HttpRequest.BodyPublishers.ofString(body))
                .build();
        var resp = http.send(req, HttpResponse.BodyHandlers.ofString());
        assertThat(resp.statusCode()).isEqualTo(200);
        return json.readTree(resp.body()).path("token").asText();
    }

    private JsonNode getJson(int porta, String path, String token) throws Exception {
        var req = HttpRequest.newBuilder(URI.create("http://127.0.0.1:" + porta + path))
                .header("Authorization", "Bearer " + token)
                .GET()
                .build();
        var resp = http.send(req, HttpResponse.BodyHandlers.ofString());
        assertThat(resp.statusCode()).isEqualTo(200);
        return json.readTree(resp.body());
    }

    private JsonNode putJson(int porta, String path, String token, Object payload) throws Exception {
        var req = HttpRequest.newBuilder(URI.create("http://127.0.0.1:" + porta + path))
                .header("Authorization", "Bearer " + token)
                .header("Content-Type", "application/json")
                .PUT(HttpRequest.BodyPublishers.ofString(json.writeValueAsString(payload)))
                .build();
        var resp = http.send(req, HttpResponse.BodyHandlers.ofString());
        assertThat(resp.statusCode()).isEqualTo(200);
        return json.readTree(resp.body());
    }
